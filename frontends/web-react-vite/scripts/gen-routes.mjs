import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const app = readFileSync('src/App.tsx', 'utf8');
const permissions = readFileSync('src/features/auth/permissions.ts', 'utf8');

const codes = Object.fromEntries([...permissions.matchAll(/(\w+):\s*'([A-Z_]+)'/g)].map(m => [m[1], m[2]]));

const entries = [];
for (const m of app.matchAll(/<Route\s+path="([^"]+)"\s+element=\{([\s\S]*?)\}\s*\/>/g)) {
  const [, path, element] = m;
  if (path === '*' || path.startsWith('/auth/') || path === '/required') continue;
  const guard = /<RequirePermission\s+permission=\{([^}]+?)\}>/.exec(element);
  const permission = guard ? [...guard[1].matchAll(/P\.(\w+)/g)].map(x => codes[x[1]]).filter(Boolean) : [];
  entries.push({ path, permission });
}

const unique = [...new Map(entries.map(e => [e.path, e])).values()].sort((a, b) => a.path.localeCompare(b.path));
const body = `// Generated by scripts/gen-routes.mjs from src/App.tsx. Do not edit; run \`npm run gen:routes\`.

export interface RouteEntry { path: string; /** Any one of these opens it; empty means anyone signed in. */ permission: string[] }

/** Every screen the app declares. */
export const ROUTES: RouteEntry[] = ${JSON.stringify(unique, null, 2)};

/** The ones a menu entry can point at: no parameter in the path. */
export const MENU_ROUTES: RouteEntry[] = ROUTES.filter(r => !r.path.includes(':'));

export const KNOWN_ROUTES: ReadonlySet<string> = new Set(ROUTES.map(r => r.path));
`;
mkdirSync('src/routes', { recursive: true });
writeFileSync('src/routes/manifest.ts', body);
console.log(unique.length, 'routes');
